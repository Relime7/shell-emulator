# Общие функции для демонстрационных скриптов.
cd "$(dirname "${BASH_SOURCE[0]}")/../.." || exit 1
PY="${PYTHON:-python3}"

# run КОМАНДА...  - показать команду, выполнить (stdin пуст), показать код возврата
run() {
  echo
  echo "\$ $*"
  "$@" < /dev/null
  echo "[код возврата: $?]"
}

# run_stdin 'ТЕКСТ' КОМАНДА... - то же, но подаёт ТЕКСТ на stdin (интерактивный диалог)
run_stdin() {
  local input="$1"; shift
  echo
  echo "\$ printf '...' | $*"
  printf '%b' "$input" | "$@"
  echo "[код возврата: ${PIPESTATUS[1]}]"
}

section() { echo; echo "================================================================"; echo "== $*"; echo "================================================================"; }
